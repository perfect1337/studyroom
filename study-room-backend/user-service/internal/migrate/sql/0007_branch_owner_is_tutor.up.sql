-- 0007_branch_owner_is_tutor.up.sql
-- Позволяет владельцу филиала (role=branch_owner) дополнительно вести
-- преподавательскую деятельность внутри своего же аккаунта — переключаться
-- в интерфейсе на "версию учителя" (тот же UI/функционал, что у обычного
-- tutor: назначение себе курсов, задания, тесты), не заводя отдельный
-- логин. Флаг включается им самим через PATCH /users/me/tutor-mode
-- (см. UserHandler.SetTutorMode) — по умолчанию выключен у всех.
--
-- Для role=tutor флаг не используется вовсе (у них право уже есть по самой
-- роли), поэтому осмыслен только в связке с role=branch_owner — остальным
-- ролям null/false ничего не даёт и не отнимает.
ALTER TABLE users
    ADD COLUMN IF NOT EXISTS is_tutor BOOLEAN NOT NULL DEFAULT false;
