-- 0005_student_class_number.up.sql
-- Класс ученика (student_profiles.class_info) становится обязательным при
-- регистрации и должен быть чистым числом 1..11, а не произвольным текстом
-- ("10А", "выпускной" и т.п.) — это нужно, чтобы автоматическое повышение
-- класса каждый учебный год (1 сентября, см. internal/promotion) могло
-- надёжно инкрементировать значение и понять, кто уже закончил 11 класс.
--
-- CHECK добавлен как NOT VALID: он проверяется для всех НОВЫХ и
-- ИЗМЕНЯЕМЫХ строк начиная с этой миграции, но не требует, чтобы уже
-- существующие в БД строки (которые могли быть введены раньше как
-- свободный текст) немедленно ему соответствовали — иначе миграция могла
-- бы упасть на проде из-за старых "грязных" данных. Такие строки останутся
-- как есть и будут скорректированы вручную либо отфильтрованы job'ом
-- повышения класса (он игнорирует значения, не проходящие тот же формат).
ALTER TABLE student_profiles
    ADD CONSTRAINT class_info_is_grade_number
    CHECK (class_info IS NULL OR class_info ~ '^([1-9]|1[01])$')
    NOT VALID;

-- last_promoted_year — учебный год (число вроде 2026, означающее учебный
-- год 2026/2027), в котором ученику последний раз повышали класс. Нужно,
-- чтобы job повышения классов был идемпотентным: если он отработал уже в
-- этом учебном году (или его пришлось перезапустить после сбоя в тот же
-- день), повторный проход не повысит класс ещё раз.
ALTER TABLE student_profiles ADD COLUMN last_promoted_year INTEGER;
