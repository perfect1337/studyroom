-- 0006_refresh_token_grace.up.sql
-- Раньше ротация refresh-токена (POST /auth/refresh) делала жёсткий
-- DELETE старой записи и создавала новую. Из-за этого пользователя иногда
-- "выкидывало" случайно при перезагрузке страницы: если ответ с новым
-- Set-Cookie не долетал до браузера (обрыв соединения ровно в момент
-- reload, две почти одновременные вкладки/запроса и т.п.), старый токен
-- уже был удалён на бэкенде, а новый браузер так и не увидел — следующий
-- /auth/refresh неизбежно проваливался.
--
-- Вместо DELETE теперь "мягкая" ротация: помечаем токен revoked_at, но
-- ещё какое-то время (grace-период, см. auth_repository.go) разрешаем
-- предъявить его повторно — это трактуется как гонка/потерянный ответ,
-- а не как компрометация, и просто выдаёт новую пару токенов ещё раз.
-- Предъявление токена уже ЗА пределами grace-периода — признак кражи
-- (лишний реиспользованный токен), тогда гасим все сессии пользователя.

ALTER TABLE refresh_tokens
    ADD COLUMN IF NOT EXISTS revoked_at TIMESTAMPTZ;

-- Старые (просроченные и давно отозванные) строки больше не удаляются
-- сразу при ротации, поэтому подчищаем задним числом то, что накопилось
-- бы раньше — таблица не растёт бесконтрольно на старте.
DELETE FROM refresh_tokens WHERE expires_at < now();
