-- 0007_in_app_channel.up.sql
-- Добавляет канал 'in_app' — см. internal/notifier/notifier.go, Notifier.Send.
-- Раньше "уведомление" в понимании GET /notifications (колокольчик в веб-
-- интерфейсе) было ПОБОЧНЫМ продуктом реальной доставки по внешним каналам:
-- Notifier.Send создавал по одной строке notifications НА КАЖДЫЙ включённый
-- канал (email/telegram/whatsapp/max), и ListByUser отдавала их все как есть.
-- Отсюда два бага одновременно:
--   1) пользователь с несколькими включёнными каналами (например, owner с
--      email+telegram) видел одно и то же уведомление в колокольчике
--      ПРОДУБЛИРОВАННЫМ — по строке на канал;
--   2) пользователь без резолвящегося контакта ни по одному каналу
--      (например, branch_owner, для которого ещё не пришёл/не обработан
--      user.updated с email — см. events/subscriber.go, upsertUserRef)
--      не получал уведомление вообще НИГДЕ, даже в самом вебе, потому что
--      ни одной строки notifications для него не создавалось (см. Notifier.
--      Send: "no enabled channels for user").
-- Теперь Notifier.Send всегда создаёт одну запись с channel='in_app' —
-- она ничего никуда не "доставляет" (сразу status='sent'), это и есть
-- то, что показывает колокольчик, независимо от внешних каналов. Внешние
-- каналы (email/telegram/whatsapp/max) по-прежнему создаются по настройкам
-- пользователя, но ListByUser их больше не отдаёт — см. NotificationRepository.
--
-- ВАЖНО: ALTER TYPE ... ADD VALUE нельзя использовать в одной транзакции
-- с последующим использованием этого значения, поэтому миграция состоит
-- только из ADD VALUE (тот же приём, что в 0006).

ALTER TYPE notification_channel ADD VALUE IF NOT EXISTS 'in_app';
