// Общая валидация телефона для всех форм (регистрация, добавление
// преподавателя/ученика и т.д.). Разрешаем только цифры и один ведущий "+",
// всё остальное (буквы, пробелы, скобки при вводе руками) отфильтровываем.

// Используется в onChange инпута: обрезает всё, что не цифра/ведущий "+".
export function sanitizePhoneInput(raw) {
  if (!raw) return "";
  const hasPlus = raw.trim().startsWith("+");
  const digits = raw.replace(/\D/g, "");
  return (hasPlus ? "+" : "") + digits;
}

// Для финальной проверки перед отправкой на бэкенд (например, в onSubmit).
// Считаем валидным непустой номер из 10-15 цифр (с необязательным "+" впереди).
export function isValidPhone(value) {
  if (!value) return true; // телефон необязателен — пустое значение не ошибка
  return /^\+?\d{10,15}$/.test(value);
}
